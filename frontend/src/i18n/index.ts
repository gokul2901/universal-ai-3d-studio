export function t(key: string, lang: string = "en"): string {
  const langKey = lang.toLowerCase().split("-")[0];
  if (UI_TRANSLATIONS[langKey] && UI_TRANSLATIONS[langKey][key]) {
    return UI_TRANSLATIONS[langKey][key];
  }
  return UI_TRANSLATIONS["en"][key] || key;
}

export function isRTL(lang: string = "en"): boolean {
  const code = lang.toLowerCase().split("-")[0];
  return code === "ar" || code === "ur";
}
